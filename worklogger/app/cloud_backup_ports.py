"""Boundaries for personal snapshots, encrypted archives, and remote objects."""

from typing import Protocol
from worklogger.domain.cloud_backup import StoredObject


class BackupObjectStore(Protocol):
    def test_connection(self) -> None: ...
    def get(self, key: str, *, limit: int) -> StoredObject | None: ...
    def put(self, key: str, data: bytes, *, expected_etag: str | None) -> None: ...
    def delete(self, key: str) -> None: ...


class PersonalDataStore(Protocol):
    def capture(self) -> bytes: ...
    def restore(self, document: bytes, *, expected_digest: str, before_replace, sync_state=None) -> str: ...


class BackupArchive(Protocol):
    def encode(self, document: bytes, *, encrypted: bool, passphrase: str = "") -> bytes: ...
    def decode(self, content: bytes, *, passphrase: str = "") -> bytes: ...
