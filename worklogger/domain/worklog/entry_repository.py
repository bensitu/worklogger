"""Storage contracts for independently editable time entries."""

from datetime import date, datetime
from typing import Protocol

from worklogger.domain.worklog.models import WorkLog
from worklogger.domain.worklog.search import EntryCursor, EntryFilter, EntryPage
from worklogger.domain.worklog.editing import EntryChangeInfo
from worklogger.domain.projects.models import WorkContext
from worklogger.domain.worklog.replacement import EntryReplacement


class TimeEntryRepository(Protocol):
    def search_entries(self, user_id: int, criteria: EntryFilter, *, cursor: EntryCursor | None = None, limit: int = 100) -> EntryPage: ...
    def list_for_day(self, user_id: int, day: date) -> tuple[WorkLog, ...]: ...
    def get_entry(self, user_id: int, entry_id: int) -> WorkLog | None: ...
    def save_entry(self, record: WorkLog, *, timer_change: tuple[str | None, str | None] | None = None,
                   remember_work_mode: bool = False) -> WorkLog: ...
    def delete_entry(self, user_id: int, entry_id: int, revision: int, *, timer_change: tuple[str | None, str | None] | None = None) -> None: ...
    def change_timer(self, user_id: int, expected: str | None, value: str | None) -> None: ...
    def latest_change(self, user_id: int) -> EntryChangeInfo | None: ...
    def split_entry(self, user_id: int, record: WorkLog, first_minutes: int) -> tuple[WorkLog, ...]: ...
    def split_entry_at(self, user_id: int, record: WorkLog, cut: datetime) -> tuple[WorkLog, ...]: ...
    def preview_replacement(self, user_id: int, incoming: WorkLog, original: WorkLog | None = None) -> EntryReplacement: ...
    def replace_overlap(self, user_id: int, plan: EntryReplacement, *, keep_outside: bool,
                        remember_work_mode: bool = False) -> WorkLog: ...
    def merge_entries(self, user_id: int, left: WorkLog, right: WorkLog) -> WorkLog: ...
    def convert_historical_break(self, user_id: int, record: WorkLog, first_minutes: int) -> tuple[WorkLog, ...]: ...
    def undo_change(self, user_id: int, change_id: int) -> tuple[WorkLog, ...]: ...
    def associate_entries(self, user_id: int, records: tuple[WorkLog, ...], context: WorkContext) -> tuple[WorkLog, ...]: ...
